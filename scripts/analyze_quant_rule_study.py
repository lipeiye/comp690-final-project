"""Tables for the session-1 precision maps of scripts/quant_rule_study.py (post-test, exploratory).

Reads results/supplementary/quant_rule_study/protocol.json and its run records (no EEG) and
writes, in the same directory:

  settings.csv   every setting against float/float and against 8/8, pooled over all 17
                 conditions and for each condition: accuracy, change, interval, participants
                 losing more than 2 points, weight bytes and bit-operations
  maps.csv       how often each tensor keeps 8 bits in the per-model ("own") maps
  summary.md, analysis.json

Seeds (and, in pooled rows, conditions) are averaged within each participant, then the nine
participants summarized with the frozen percentile bootstrap (10,000 resamples, 95 %, seed 690).
"""

from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd

from mibci import fakequant
from mibci.artifacts import sha256, write_json
from mibci.paths import RESULTS_DIR, display
from mibci.stats import FROZEN_BOOTSTRAP, bootstrap_ci

OUT = RESULTS_DIR / "supplementary/quant_rule_study"
PLAN = OUT / "protocol.json"
POOLED = "all conditions"
SHOWN = ("full-22", "relevance-16", "relevance-16-prune50", "relevance-8")
MATERIAL_PP, TOLERANCE = 2.0, 1e-9


def load() -> tuple[dict, list[dict]]:
    plan = json.loads(PLAN.read_text())
    digest = sha256(PLAN)
    records = []
    for job in plan["jobs"]:
        path = OUT / "runs" / f"{job['name']}.json"
        if not path.is_file():
            raise SystemExit(f"missing {display(path)}; finish scripts/quant_rule_study.py --stage run")
        record = json.loads(path.read_text())
        if record["protocol_sha256"] != digest or record["maps"] != job["maps"]:
            raise SystemExit(f"{display(path)} does not belong to this plan")
        records.append(record)
    return plan, records


def frame(records: list[dict]) -> pd.DataFrame:
    rows = [{"subject": r["subject"], "seed": r["seed"], "condition": r["condition"], "setting": key,
             "acc": 100 * s["primary"]["acc"], "session1": 100 * s["session1_acc"], "weight_bytes": s["weight_bytes"],
             "bops": s["bops"]}
            for r in records for key, s in r["settings"].items()]  # fmt: skip
    return pd.DataFrame(rows)


def compare(df: pd.DataFrame, setting: str, reference: str) -> dict:
    wide = df.groupby(["subject", "setting"]).acc.mean().unstack("setting")
    diff = (wide[setting] - wide[reference]).to_numpy()
    low, high = bootstrap_ci(diff, FROZEN_BOOTSTRAP)
    return {"diff_pp": float(diff.mean()), "low_pp": low, "high_pp": high, "worst_pp": float(diff.min()),
            "n_lose_more_than_2": int((diff < -(MATERIAL_PP + TOLERANCE)).sum())}  # fmt: skip


def settings_table(df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for condition in (POOLED, *sorted(df.condition.unique())):
        part = df if condition == POOLED else df[df.condition == condition]
        for setting in part.setting.unique():
            mine = part[part.setting == setting]
            rows.append({"condition": condition, "setting": setting, "accuracy": float(mine.acc.mean()),
                         "session1_accuracy": float(mine.session1.mean()),
                         "weight_bytes": float(mine.weight_bytes.mean()),
                         "bops_millions": float(mine.bops.mean() / 1e6),
                         **{f"vs_float_{k}": v for k, v in compare(part, setting, "float/float").items()},
                         **{f"vs_8_8_{k}": v for k, v in compare(part, setting, "8/8").items()}})  # fmt: skip
    return pd.DataFrame(rows)


def map_table(records: list[dict]) -> pd.DataFrame:
    rows = []
    for key in sorted({k for r in records for k in r["maps"] if k.startswith("own")}):
        for kind, names in (("weights", fakequant.WEIGHTED), ("activations", fakequant.POINTS)):
            for name in names:
                share = np.mean([r["maps"][key][kind][name] == 8 for r in records])
                rows.append({"rule": key, "kind": kind, "tensor": name, "share_at_8_bits": float(share)})
    return pd.DataFrame(rows)


def interval(row, prefix: str) -> str:
    return f"{row[prefix + 'diff_pp']:+.2f} [{row[prefix + 'low_pp']:+.2f}, {row[prefix + 'high_pp']:+.2f}]"


def describe(spec: dict) -> str:
    def part(kind: str) -> str:
        eight = [n for n, b in spec[kind].items() if b == 8]
        return f"{kind} at 8 bits: {', '.join(eight) if eight else 'none'}; the rest 4"

    return f"{part('weights')}. {part('activations')}"


def summary(plan: dict, table: pd.DataFrame, maps: pd.DataFrame, check: dict) -> str:
    order = ["float/float", "8/8", "4/8", "pooled-2", "pooled-0.5", "own-2", "own-0.5"]
    lines = ["# Session-1 precision maps on session 2 (generated by scripts/analyze_quant_rule_study.py)", "",
             "Every archived final model (459) was rounded with mixed-precision maps read from session-1 "
             "sensitivity only: a tensor keeps 8 bits if rounding it alone to 4 bits cost more than T points of "
             "session-1 accuracy (pooled: averaged over participants; own: that model's own number), else 4 bits. "
             "No retraining. Exploratory: the thresholds (2 and 0.5 points) were picked after the bit-width study's "
             "session-2 results were known.", "",
             f"- pooled-2: {describe(plan['pooled_maps']['pooled-2'])}.",
             f"- pooled-0.5: {describe(plan['pooled_maps']['pooled-0.5'])}.",
             f"- Check: float/float, 8/8 and 4/8 were scored again; {check['differ']} of {check['total']} of these "
             f"accuracies differ from the bit-width study's records, the largest by {check['largest']:.4f} (one trial "
             "whose rounding landed on the other side of a grid step).", "",
             "Accuracy on artifact-free session-2 trials; seeds and conditions averaged within each participant; "
             "brackets: 95% participant bootstrap; 'n > 2': participants losing more than 2 points. Weight bytes and "
             "bit-operations are counted, not measured; below 8 bits nothing ran on a real low-bit kernel.", "",
             "| condition | setting | accuracy % | minus float/float (pp) [95%] | n > 2 | minus 8/8 (pp) [95%] | n > 2 "
             "| weight bytes | bit-ops (M) |",
             "| --- | --- | ---: | --- | ---: | --- | ---: | ---: | ---: |"]  # fmt: skip
    for condition in (POOLED, *SHOWN):
        part = table[table.condition == condition].set_index("setting")
        for setting in order:
            r = part.loc[setting]
            lines.append(f"| {condition} | {setting} | {r.accuracy:.2f} | {interval(r, 'vs_float_')} | "
                         f"{r.vs_float_n_lose_more_than_2} | {interval(r, 'vs_8_8_')} | "
                         f"{r.vs_8_8_n_lose_more_than_2} | {r.weight_bytes:,.0f} | "
                         f"{r.bops_millions:,.1f} |")  # fmt: skip
    first = maps[maps["rule"] == maps["rule"].iloc[0]]
    header = " | ".join(f"{kind}: {name}" for kind, name in first[["kind", "tensor"]].to_numpy())
    lines += ["", "## Per-model maps: share of the 459 models that keep a tensor at 8 bits", "",
              f"| map | {header} |", "| --- |" + " ---: |" * len(first)]  # fmt: skip
    for key in maps["rule"].unique():
        shares = maps[maps["rule"] == key].share_at_8_bits
        lines.append(f"| {key} | " + " | ".join(f"{100 * s:.0f}%" for s in shares) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    plan, records = load()
    df = frame(records)
    table = settings_table(df)
    maps = map_table(records)
    values = [abs(v) for r in records for v in r["difference_from_bit_width_study"].values()]
    check = {"differ": sum(v > 0 for v in values), "total": len(values), "largest": max(values)}
    table.to_csv(OUT / "settings.csv", index=False)
    maps.to_csv(OUT / "maps.csv", index=False)
    (OUT / "summary.md").write_text(summary(plan, table, maps, check))
    write_json(OUT / "analysis.json", {"settings": table.to_dict("records"), "reference_check": check,
                                       "plan_sha256": sha256(PLAN)})  # fmt: skip
    print((OUT / "summary.md").read_text())


if __name__ == "__main__":
    main()
