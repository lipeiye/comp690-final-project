"""Would a better redundancy measure change which electrodes are chosen? (training day only)

The midterm slides proposed a follow-up: band power rises and falls together over the
whole scalp, so remove that shared swing before measuring redundancy, then retrain.
Before spending training runs on it, this script checks on session-1 data alone how
many electrodes the rule would actually swap, for the original redundancy and for the
common-mode-removed one, at the original penalty 0.5 and at 1.0. It also compares the
spread of the two terms the greedy rule trades off. No model is trained and session 2
is never read, so nothing here depends on test results.

Writes results/supplementary/redundancy_check/summary.json and summary.md.
"""

from __future__ import annotations

import argparse

import numpy as np
from scipy.stats import spearmanr

from mibci import data, selection
from mibci.artifacts import write_json
from mibci.experiment import RESULTS_DIR, session1

OUT = RESULTS_DIR / "supplementary/redundancy_check"
PENALTIES = (selection.REDUNDANCY_PENALTY, 1.0)


def redundancy(logpow: np.ndarray) -> np.ndarray:
    return np.mean([np.abs(spearmanr(logpow[:, :, b]).statistic) for b in range(logpow.shape[-1])], axis=0)


def term_spread(rel: np.ndarray, red: np.ndarray, penalty: float, k: int) -> tuple[float, float]:
    """Mean spread (SD over the remaining candidates) of relevance and of the penalty term
    during the first k greedy steps: the larger spread decides the order."""
    order, rel_sd, pen_sd = [int(np.argmax(rel))], [], []
    while len(order) < k:
        candidates = [c for c in range(len(rel)) if c not in order]
        pen = np.array([penalty * red[c, order].mean() for c in candidates])
        rel_sd.append(rel[candidates].std())
        pen_sd.append(pen.std())
        order.append(candidates[int(np.argmax(rel[candidates] - pen))])
    return float(np.mean(rel_sd)), float(np.mean(pen_sd))


def main() -> None:
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    off = ~np.eye(len(data.EEG_CHANNELS), dtype=bool)
    participants = []
    for subject in data.SUBJECTS:
        X, y, train, _ = session1(subject, "final")
        logpow = selection.band_log_power(X[train])
        rel = selection.relevance(logpow, y[train])
        measures = {
            "original": redundancy(logpow),
            # subtract, per trial and band, the log power averaged over all electrodes
            "common_mode_removed": redundancy(logpow - logpow.mean(axis=1, keepdims=True)),
        }
        baseline = selection.greedy_ranking(rel, measures["original"], 0.0)
        row = {"subject": subject}
        for name, red in measures.items():
            row[name] = {"mean_abs_correlation": float(red[off].mean()), "sd_abs_correlation": float(red[off].std())}
            for penalty in PENALTIES:
                order = selection.greedy_ranking(rel, red, penalty)
                rel_sd, pen_sd = term_spread(rel, red, penalty, 16)
                row[name][f"penalty_{penalty}"] = {
                    "swapped_at_16": len(set(order[:16]) - set(baseline[:16])),
                    "swapped_at_8": len(set(order[:8]) - set(baseline[:8])),
                    "relevance_spread": rel_sd,
                    "penalty_spread": pen_sd,
                }
        participants.append(row)

    summary = {
        "status": "training-day description; no training, session 2 not read",
        "participants": participants,
        "overall": {},
    }
    lines = [
        "# Redundancy check on the training day (generated by scripts/redundancy_check.py)",
        "",
        "Electrodes swapped relative to the relevance-only subset, per participant (P1..P9).",
        "",
        "| redundancy measure | mean abs. correlation | penalty | swapped of 16 | participants changed "
        "| swapped of 8 | participants changed | spread of relevance / spread of penalty |",
        "| --- | ---: | ---: | --- | ---: | --- | ---: | ---: |",
    ]
    for name in ("original", "common_mode_removed"):
        corr = float(np.mean([p[name]["mean_abs_correlation"] for p in participants]))
        for penalty in PENALTIES:
            cells = [p[name][f"penalty_{penalty}"] for p in participants]
            s16, s8 = [c["swapped_at_16"] for c in cells], [c["swapped_at_8"] for c in cells]
            ratio = float(np.mean([c["relevance_spread"] / c["penalty_spread"] for c in cells]))
            summary["overall"][f"{name}_penalty_{penalty}"] = {
                "mean_abs_correlation": corr,
                "swapped_at_16": s16,
                "swapped_at_8": s8,
                "participants_changed_at_16": sum(v > 0 for v in s16),
                "participants_changed_at_8": sum(v > 0 for v in s8),
                "relevance_to_penalty_spread_ratio": ratio,
            }
            lines.append(
                f"| {name.replace('_', ' ')} | {corr:.2f} | {penalty} | {' '.join(map(str, s16))} | "
                f"{sum(v > 0 for v in s16)}/9 | {' '.join(map(str, s8))} | {sum(v > 0 for v in s8)}/9 | {ratio:.1f} |"
            )
    write_json(OUT / "summary.json", summary)
    (OUT / "summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
