"""Tests R1-R3 of scripts/replication_riemann_study.py: Riemannian against relevance selection on Lee2019.

Reads results/supplementary/replication_riemann_study/ (its plan and test records) and, for the
comparison, the relevance-K records of results/supplementary/replication_study/ (no EEG). Writes,
in the Riemannian study's directory: hypotheses.csv, per_participant.csv, summary.md and
analysis.json.

As fixed in the plan: all session-2 trials, seeds averaged within each participant, then the
54 participants summarized with the frozen percentile bootstrap (10,000 resamples, 95 %,
seed 690); each hypothesis passes when the interval's lower bound is above 0.
"""

from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd

from mibci.artifacts import sha256, write_json
from mibci.paths import RESULTS_DIR, display
from mibci.stats import FROZEN_BOOTSTRAP, bootstrap_ci

OUT = RESULTS_DIR / "supplementary/replication_riemann_study"
REPLICATION = RESULTS_DIR / "supplementary/replication_study"
TOLERANCE = 1e-9


def records(folder, plan: dict, wanted) -> list[dict]:
    digest = sha256(folder / "protocol.json")
    found = []
    for job in plan["jobs"]:
        if not wanted(job):
            continue
        path = folder / "test" / f"{job['name']}.json"
        if not path.is_file():
            raise SystemExit(f"missing {display(path)}; finish that study's evaluate stage")
        record = json.loads(path.read_text())
        if record["protocol_sha256"] != digest:
            raise SystemExit(f"{display(path)} does not belong to its plan")
        found.append(record)
    return found


def load() -> tuple[dict, pd.DataFrame]:
    plan = json.loads((OUT / "protocol.json").read_text())
    if plan["comparison_plan_sha256"] != sha256(REPLICATION / "protocol.json"):
        raise SystemExit("the replication plan changed since this study was planned")
    counts = {f"relevance-{k}" for k in plan["counts"]}
    rep_plan = json.loads((REPLICATION / "protocol.json").read_text())
    rows = [{"subject": r["subject"], "seed": r["seed"], "condition": r["condition"], "acc": 100 * r["acc_all"]}
            for r in records(OUT, plan, lambda j: True)]  # fmt: skip
    rows += [{"subject": r["subject"], "seed": r["seed"], "condition": r["condition"],
              "acc": 100 * r["scores"]["fp32"]["acc_all"]}
             for r in records(REPLICATION, rep_plan, lambda j: j["condition"] in counts)]  # fmt: skip
    return plan, pd.DataFrame(rows)


def main() -> None:
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    plan, df = load()
    person = df.groupby(["subject", "condition"]).acc.mean().unstack("condition")
    rows = []
    for key, k in zip(("R1", "R2", "R3"), plan["counts"], strict=True):
        diff = (person[f"riemann-{k}"] - person[f"relevance-{k}"]).to_numpy()
        low, high = bootstrap_ci(diff, FROZEN_BOOTSTRAP)
        rows.append({"hypothesis": key, "electrodes": k, "riemann_pct": float(person[f"riemann-{k}"].mean()),
                     "relevance_pct": float(person[f"relevance-{k}"].mean()), "diff_pp": float(diff.mean()),
                     "low_pp": low, "high_pp": high, "better": int((diff > TOLERANCE).sum()),
                     "worse": int((diff < -TOLERANCE).sum()), "n": len(diff), "met": bool(low > 0)})  # fmt: skip
    table = pd.DataFrame(rows)
    table.to_csv(OUT / "hypotheses.csv", index=False)
    person.to_csv(OUT / "per_participant.csv")
    lines = [
        "# Riemannian electrode selection on Lee2019 (generated by scripts/analyze_replication_riemann_study.py)", "",
        f"Plan written {plan['created_at']}, before any Lee2019 session-2 trial was scored; the hypothesis comes "
        "from an exploratory BCI IV 2a result. Accuracy on all session-2 trials (two classes, chance 50%), seeds "
        "averaged within each of the 54 participants; 95% participant bootstrap interval. 'Met' means the "
        "interval's lower bound is above 0, as the plan states.", "",
        "| | electrodes | Riemannian % | relevance % | difference (pp) [95%] | better/worse | met |",
        "| --- | ---: | ---: | ---: | --- | --- | --- |",
    ]  # fmt: skip
    lines.extend(
        f"| {r['hypothesis']} | {r['electrodes']} | {r['riemann_pct']:.2f} | {r['relevance_pct']:.2f} | "
        f"{r['diff_pp']:+.2f} [{r['low_pp']:+.2f}, {r['high_pp']:+.2f}] | {r['better']}/{r['worse']} | "
        f"{'yes' if r['met'] else 'no'} |"
        for r in rows
    )
    lines += ["", "One dataset, one two-class task, 54 people. An interval that contains zero is not evidence "
              "that the two rules are equal.", ""]  # fmt: skip
    (OUT / "summary.md").write_text("\n".join(lines))
    means = {c: float(np.mean(person[c])) for c in person}
    write_json(OUT / "analysis.json", {"hypotheses": rows, "plan_sha256": sha256(OUT / "protocol.json"),
                                       "mean_accuracy_pct": means})  # fmt: skip
    print((OUT / "summary.md").read_text())


if __name__ == "__main__":
    main()
