"""The int8 FIR kernel for EEGNet's temporal layer on Cortex-M (mcu/kernels/), and its build.

scripts/mcu_study.py found that CMSIS-NN runs the temporal convolution, 16 (swapped order) or 8 per
electrode (original order) FIR filters of 64 taps, through its general convolution paths: about 10.7
instructions per multiply-accumulate on the Cortex-M4, where the DSP extension's SMLAD does two in one
instruction and Helium's VMLADAVA sixteen. mcu/kernels/fir_s8.c is that layer as a filter bank (plain C,
DSP and Helium paths); mcu/kernels/eegnet_int8_fir.c is mcu/eegnet_int8.c (pinned) with only the temporal
layer replaced. This module writes the kernel's header and builds the network:

fir_taps       the temporal layer's int8 taps as (filters, taps) from a network of mibci.mcu.quantize:
               the original order's CONV_2D weights (F1, 1, K, 1), the swapped order's DEPTHWISE
               weights (1, K, F1*D)
fir_layer      the kernel's arithmetic in NumPy (offset input, zero-point padding, exact sum, the
               library's requantization), checked against mibci.mcu's reference in tests/test_mcu_kernels.py
write_header   fir.h with the taps in int8 and int16 and their sums
link           the harness of mcu/ with the FIR network, for one core and board (mibci.mcu_build's
               compiler flags, library and linker script)
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from mibci import mcu, mcu_build
from mibci.mcu_build import CORES, MCU_DIR, PROGRAM_FLAGS

KERNEL_DIR = MCU_DIR / "kernels"
SOURCES = ("eegnet_int8_fir.c", "fir_s8.c")
HARNESS = ("main.c", "semihost.c", "startup.c")


def temporal_layer(qnet: dict) -> dict:
    return qnet["layers"][0 if qnet["order"] == "original" else 1]


def fir_taps(qnet: dict) -> np.ndarray:
    w = temporal_layer(qnet)["w"]
    taps = w[:, 0, :, 0] if qnet["order"] == "original" else w[0].T
    return np.ascontiguousarray(taps).astype(np.int8)


def fir_layer(qnet: dict, x: np.ndarray) -> np.ndarray:
    """The temporal layer as fir_bank_s8 computes it; x is the layer's int8 input in NHWC."""
    q = temporal_layer(qnet)
    taps = fir_taps(qnet).astype(np.int64)
    k = taps.shape[1]
    pad = k // 2
    rows = x[:, :, :, 0] if qnet["order"] == "original" else x[:, 0, :, :].transpose(0, 2, 1)  # (N, rows, T)
    padded = np.pad(rows.astype(np.int64) - q["in_zero"], ((0, 0), (0, 0), (pad, pad)))
    windows = np.lib.stride_tricks.sliding_window_view(padded, k, axis=2)  # (N, rows, outputs, k)
    if qnet["order"] == "original":  # every row through every filter: (N, rows, outputs, filters)
        acc = np.einsum("nrtk,fk->nrtf", windows, taps) + q["b"]
        out = mcu.requantize(acc, q["multiplier"], q["shift"])
    else:  # row c through filter c: (N, 1, outputs, channels)
        acc = np.einsum("nctk,ck->nct", windows, taps) + q["b"][None, :, None]
        out = mcu.requantize(acc, q["multiplier"][None, :, None], q["shift"][None, :, None])
        out = out.transpose(0, 2, 1)[:, None]
    return np.clip(out + q["out_zero"], -128, 127).astype(np.int8)


def _c_array(ctype: str, name: str, values: np.ndarray) -> str:
    flat = [str(int(v)) for v in np.asarray(values).ravel()]
    lines = [", ".join(flat[i : i + 24]) for i in range(0, len(flat), 24)]
    head = f"static const {ctype} {name}[{len(flat)}] __attribute__((aligned(16))) = {{\n    "
    return head + ",\n    ".join(lines) + "\n};\n"


def write_header(directory: Path, qnet: dict) -> None:
    taps = fir_taps(qnet)
    body = [
        "/* Generated by mibci.mcu_kernels; do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define FIR_FILTERS {taps.shape[0]}",
        _c_array("int8_t", "fir_w8", taps),
        _c_array("int16_t", "fir_w16", taps.astype(np.int16)),
        _c_array("int32_t", "fir_wsum", taps.astype(np.int64).sum(1)),
    ]
    (Path(directory) / "fir.h").write_text("\n".join(body) + "\n")


def link(t, core: str, headers: Path, out: Path, board: str, scratch: int, stack: int) -> Path:
    """mibci.mcu_build.link for the FIR network: the same flags, CMSIS-NN library and linker script."""
    out.mkdir(parents=True, exist_ok=True)
    elf = out / "net.elf"
    lib = mcu_build.library(t, core, out.parent.parent / "_lib")
    script = mcu_build.linker_script(board, stack, out / "board.ld")
    sources = [MCU_DIR / s for s in HARNESS] + [KERNEL_DIR / s for s in SOURCES]
    mcu_build._run([t["gcc"], *CORES[core]["flags"], *PROGRAM_FLAGS, f"-DSCRATCH_BYTES={scratch}", f"-I{headers}",
                    f"-I{KERNEL_DIR}", f"-I{MCU_DIR}", f"-I{t['cmsis'] / 'Include'}", *sources, lib,
                    "--specs=nano.specs", "-nostartfiles", "-Wl,--gc-sections", f"-Wl,-Map,{out / 'net.map'}",
                    "-T", script, "-lm", "-o", elf])  # fmt: skip
    return elf
